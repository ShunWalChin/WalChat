alter table public.instagram_accounts
  add column if not exists account_type text,
  add column if not exists connected_by uuid references auth.users(id) on delete set null,
  add column if not exists subscribed_fields text[] not null default '{}',
  add column if not exists permissions_validated_at timestamptz,
  add column if not exists token_refresh_after timestamptz,
  add column if not exists last_token_refresh_at timestamptz,
  add column if not exists last_sync_at timestamptz,
  add column if not exists connection_error text;

alter table public.instagram_accounts
  drop constraint if exists instagram_accounts_account_type_check;

alter table public.instagram_accounts
  add constraint instagram_accounts_account_type_check
  check (account_type is null or account_type in ('BUSINESS', 'CREATOR'));

create table public.integration_credentials (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  instagram_account_id uuid references public.instagram_accounts(id) on delete cascade,
  provider text not null check (provider in ('meta', 'openai', 'google')),
  credential_type text not null check (credential_type in ('access_token', 'api_key')),
  scope_key text not null,
  encrypted_value text not null,
  expires_at timestamptz,
  last_refreshed_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (workspace_id, provider, credential_type, scope_key)
);

create table public.integration_oauth_states (
  state_hash text primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  provider text not null check (provider = 'meta'),
  redirect_after text not null default '/configuracoes',
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default timezone('utc', now())
);

create table public.ai_provider_settings (
  workspace_id uuid primary key references public.workspaces(id) on delete cascade,
  provider text not null default 'openai' check (provider in ('openai', 'google')),
  model text not null default 'gpt-5.6-sol',
  reasoning_effort text not null default 'low' check (reasoning_effort in ('none', 'low', 'medium', 'high')),
  response_verbosity text not null default 'low' check (response_verbosity in ('low', 'medium', 'high')),
  max_output_tokens integer not null default 500 check (max_output_tokens between 100 and 2000),
  is_enabled boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

alter table public.ai_agents
