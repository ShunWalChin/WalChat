-- O backend com service_role é o único leitor/escritor de credenciais e states.
revoke all on public.integration_credentials from anon, authenticated;
revoke all on public.integration_oauth_states from anon, authenticated;
revoke all on public.integration_audit_logs from anon, authenticated;
grant select on public.integration_audit_logs to authenticated;
grant all on public.integration_credentials to service_role;
grant all on public.integration_oauth_states to service_role;
grant all on public.ai_provider_settings to service_role;
grant all on public.integration_audit_logs to service_role;
grant usage, select on sequence public.integration_audit_logs_id_seq to service_role;

